def test_answer_key_parser_is_order_independent():
    text = (
        "75:(1.00), 12:(3), 1:(4), 50:(9), 23:(246), 2:(4), "
        "47:(332), 21:(5), 3:(2), 74:(5)"
    )
    answers = parse(text)
    assert answers == {
        75: "1.00", 12: "3", 1: "4", 50: "9", 23: "246",
        2: "4", 47: "332", 21: "5", 3: "2", 74: "5",
    }


def test_answer_key_parser_accepts_mixed_order_and_mixed_syntax():
    text = (
        "Q7 = (3)\n"
        "3) (2)\n"
        "Question 10: (1)\n"
        "[2] (4)\n"
        "5 A\n"
        "1 -> (4)\n"
        "4. D\n"
        "6: (1)"
    )
    answers = parse(text)
    assert answers[1] == "4"
    assert answers[2] == "4"
    assert answers[3] == "2"
    assert answers[4] == "D"
    assert answers[5] == "A"
    assert answers[6] == "1"
    assert answers[7] == "3"
    assert answers[10] == "1"


def test_answer_key_parser_accepts_compact_whitespace_key():
    answers = parse("7 (3) 2 (4) 5 (2) 1 (4) 3 (2)")
    assert answers == {7: "3", 2: "4", 5: "2", 1: "4", 3: "2"}


def test_answer_key_parser_accepts_decimal_and_negative_numeric_answers():
    answers = parse("75:(1.00), 24:(-3.5), 25:(1/2), 26:(0)")
    assert answers == {75: "1.00", 24: "-3.5", 25: "1/2", 26: "0"}


